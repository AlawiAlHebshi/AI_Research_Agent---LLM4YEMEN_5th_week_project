def translate(text: str, language: str = "ar") -> str:
    """Translate owned UI copy, including fixed HTML fragments. Not user data."""
    if language != "en":
        return text
    if text in EN:
        return EN[text]
    for original in sorted(EN, key=len, reverse=True):
        text = text.replace(original, EN[original])
    return text
